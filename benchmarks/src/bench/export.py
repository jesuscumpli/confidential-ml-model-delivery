"""Renders the evaluation results as an ADR-style markdown document."""

from __future__ import annotations

import platform
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
from confidential_crypto import registry

from bench import ranking, scorecard

_FLOAT_FORMAT = ".1f"


def _md(frame: pd.DataFrame, *, index: bool = True) -> str:
    return frame.to_markdown(index=index, floatfmt=_FLOAT_FORMAT)


def _sources_section(notes: dict[str, dict[str, Any]]) -> str:
    lines: list[str] = []
    for name, entry in notes.items():
        lines.append(f"**{name}** — {entry['notes']}")
        lines.append("")
        lines.extend(f"- {s}" for s in entry["sources"])
        lines.append("")
    return "\n".join(lines)


def _deviations(best_cipher: str, best_signer: str) -> str:
    """Make any gap between the measured winner and the registry default explicit."""
    lines = []
    if best_cipher != registry.DEFAULT_CIPHER:
        lines.append(
            f"**Deviation:** the registry default `{registry.DEFAULT_CIPHER}` is not the "
            f"top-ranked cipher `{best_cipher}`. The default stands only with a written "
            "justification here (for example FIPS approval or hardware profile of the "
            "target nodes); otherwise update `DEFAULT_CIPHER` and re-export."
        )
    if best_signer != registry.DEFAULT_SIGNER:
        lines.append(
            f"**Deviation:** the registry default `{registry.DEFAULT_SIGNER}` is not the "
            f"top-ranked signature scheme `{best_signer}`; justify it here or update "
            "`DEFAULT_SIGNER` and re-export."
        )
    if not lines:
        lines.append("The registry defaults match the measured ranking.")
    return "\n\n".join(lines)


def render(cipher_results: pd.DataFrame, signer_results: pd.DataFrame) -> str:
    cipher_card, signer_card = scorecard.cipher_scorecard(), scorecard.signer_scorecard()
    cipher_notes, signer_notes = scorecard.notes()
    cipher_rank = ranking.rank(cipher_results, cipher_card, ranking.CIPHER_WEIGHTS, key="cipher")
    signer_rank = ranking.rank(signer_results, signer_card, ranking.SIGNER_WEIGHTS, key="scheme")

    cipher_view = cipher_results.copy()
    cipher_view["size_mib"] = cipher_view.pop("size_bytes") / (1 << 20)
    cipher_columns = [
        "cipher", "size_mib", "encrypt_mib_s", "decrypt_mib_s", "peak_rss_mib",
        "overhead_bytes", "nonce_bytes", "entropy_bits_per_byte", "chi_square", "tamper_detected",
    ]  # fmt: skip
    signer_columns = [
        "scheme", "keygen_ms", "sign_ms", "verify_ms", "public_key_pem_bytes",
        "signature_bytes", "deterministic",
    ]  # fmt: skip

    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    machine = f"{platform.machine()}, Python {platform.python_version()}"
    cipher_names = ", ".join(f"`{c.name}`" for c in registry.available_ciphers(include_unsafe=True))
    signer_names = ", ".join(f"`{s.name}`" for s in registry.available_signers(include_unsafe=True))
    best_cipher, best_signer = cipher_rank.index[0], signer_rank.index[0]
    deviations = _deviations(best_cipher, best_signer)
    return f"""# ADR: cipher and signature scheme selection

Generated by `benchmarks` on {generated} ({machine}). Re-run with `uv run bench run`
followed by `uv run bench export`; do not edit the tables by hand.

## Context

The producer encrypts a model artifact once and the consumer decrypts it once per
deployment. Both operations run on general-purpose CPUs. The artifact must also be
signed so the consumer can reject tampered downloads before touching the key.
The shared package `confidential-crypto` exposes every candidate behind one protocol,
so the choice is a registry default, not a code change.

## Candidates

Ciphers: {cipher_names}.
Signature schemes: {signer_names}.

`aes-256-cbc-hmac-sha256` is included only as the negative example of a hand-rolled
composition; the registry refuses it outside the evaluation.

## Measurements

### Ciphers

{_md(cipher_view[cipher_columns], index=False)}

Entropy and chi-square are sanity checks, not a ranking criterion: every correct
cipher produces bytes indistinguishable from uniform (entropy ≈ 8.0, chi-square ≈ 255).
A value far from these would indicate an implementation error (for example a
non-random nonce or ECB-like structure), nothing more.

### Signature schemes (message of {int(signer_results["message_bytes"].iloc[0]) >> 20} MiB)

{_md(signer_results[signer_columns], index=False)}

## Security scorecard (0 = unacceptable, 3 = strong)

### Ciphers

{_md(cipher_card)}

### Signature schemes

{_md(signer_card)}

## Weighted ranking

Weights (ciphers): {dict(ranking.CIPHER_WEIGHTS)}.

{_md(cipher_rank)}

Weights (signers): {dict(ranking.SIGNER_WEIGHTS)}.

{_md(signer_rank)}

## Decision

- Cipher: `{registry.DEFAULT_CIPHER}` — top-ranked production-safe candidate: `{best_cipher}`.
- Signature scheme: `{registry.DEFAULT_SIGNER}` — top-ranked candidate: `{best_signer}`.

{deviations}

## Consequences

- The artifact header carries the cipher id and is authenticated, so switching the
  default later is a producer-side configuration change; old artifacts stay readable.
- Nonce management: the selected AEAD uses random nonces; with one artifact per key
  the 2^32-message bound is irrelevant, and the consumer never encrypts.
- Post-quantum: symmetric confidentiality is already at the 128-bit PQ level with a
  256-bit key. Signatures are the PQ gap; `ml-dsa-65` is registered and measured so a
  hybrid or migration is a registry change, not a redesign.
- Evaluation-only algorithms are gated by `production_safe` and never ship in the
  service images.

## Notes and sources

### Ciphers

{_sources_section(cipher_notes)}
### Signature schemes

{_sources_section(signer_notes)}"""


def write(cipher_results: pd.DataFrame, signer_results: pd.DataFrame, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(cipher_results, signer_results), encoding="utf-8")
